export async function downloadWardsPDF(
  wards: Ward[],
  filtersOrUser?: Partial<WardFilterState> | User | null,
  userParam?: User | null
): Promise<void> {
  const isUser = filtersOrUser && ('role' in filtersOrUser || 'username' in filtersOrUser);
  const currentUser = isUser ? (filtersOrUser as User) : userParam;
  const rawFilters = isUser ? null : (filtersOrUser as Partial<WardFilterState> | null);
  const filters: WardFilterState = {
    searchTerm: rawFilters?.searchTerm || '',
    departmentId: rawFilters?.departmentId || 'All',
    wardType: rawFilters?.wardType || 'All',
    status: rawFilters?.status || 'All',
  };

  const profile = getHospitalProfile();
  const now = new Date();
  const dateStr = getDynamicDateString(now);
  const timeStr = now.toLocaleTimeString('en-PK', { hour: '2-digit', minute: '2-digit' });
  const generatedOn = `${formatDisplayDate(now)}, ${timeStr}`;
  const generatedByName = currentUser?.name || 'Prof. Dr. Tariq Saeed';
  const generatedByRole = currentUser?.role || 'Super Admin';

  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 14;

  doc.setFillColor(8, 119, 90);
  doc.rect(0, 0, pageWidth, 4, 'F');

  const hospitalName = profile.name || 'CH Sharif and Saeed Hospital';
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(15, 23, 42);
  doc.text(hospitalName, margin, 14);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text('Executive Inpatient Accommodation Master • Ward Infrastructure Setup', margin, 19);

  const regNo = getProfileFieldValue(profile.registrationNumber);
  const taxNo = getProfileFieldValue(profile.taxNumber);
  const phone = getProfileFieldValue(profile.primaryPhone);

  doc.setFontSize(8);
  doc.setTextColor(71, 85, 105);
  doc.text(`Reg No: ${regNo}   |   NTN/Tax: ${taxNo}   |   Phone: ${phone}`, margin, 24);

  // Right Title Box
  doc.setFillColor(239, 250, 245);
  doc.setDrawColor(194, 231, 219);
  doc.roundedRect(pageWidth - margin - 75, 8, 75, 18, 2, 2, 'FD');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(8, 119, 90);
  doc.text('WARD DIRECTORY', pageWidth - margin - 70, 15);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(51, 65, 85);
  doc.text(`Total Records: ${wards.length}`, pageWidth - margin - 70, 21);

  // Filter Box
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(margin, 28, pageWidth - margin * 2, 13, 2, 2, 'FD');

  const deptLabel =
    filters.departmentId === 'All'
      ? 'All Departments'
      : DepartmentService.getDepartmentById(filters.departmentId)?.name || filters.departmentId;

  const appliedFilters = [
    `Search: ${filters.searchTerm.trim() ? `"${filters.searchTerm.trim()}"` : 'None'}`,
    `Dept: ${deptLabel}`,
    `Type: ${filters.wardType}`,
    `Status: ${filters.status}`,
  ].join('  •  ');

  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text('GENERATED BY:', margin + 3, 33);
  doc.text('GENERATED ON:', margin + 65, 33);
  doc.text('ACTIVE FILTERS:', margin + 130, 33);

  doc.setFont('helvetica', 'bold');
  doc.setTextColor(30, 41, 59);
  doc.text(`${generatedByName} (${generatedByRole})`, margin + 3, 38);
  doc.text(generatedOn, margin + 65, 38);
  doc.setFont('helvetica', 'normal');
  doc.text(appliedFilters, margin + 130, 38);

  const headers = [
    ['Ward Code', 'Ward Name', 'Department', 'Type', 'Floor / Location', 'Rooms', 'Total Beds', 'Available', 'Status'],
  ];

  const body = wards.map((w) => [
    w.code,
    w.name,
    w.departmentName,
    w.wardType,
    w.location ? `${w.floor || ''} - ${w.location}` : w.floor || 'N/A',
    String(w.roomCount),
    String(w.bedCount),
    String(w.availableBeds ?? 0),
    w.status,
  ]);

  autoTable(doc, {
    head: headers,
    body: body,
    startY: 44,
    margin: { left: margin, right: margin, bottom: 16 },
    theme: 'grid',
    styles: { fontSize: 8, cellPadding: 2, lineColor: [226, 232, 240], lineWidth: 0.1, textColor: [30, 41, 59] },
    headStyles: { fillColor: [239, 250, 245], textColor: [8, 119, 90], fontStyle: 'bold', lineColor: [194, 231, 219] },
    columnStyles: {
      0: { fontStyle: 'bold', cellWidth: 26 },
      1: { cellWidth: 50 },
      2: { cellWidth: 50 },
      3: { cellWidth: 28 },
      4: { cellWidth: 48 },
      5: { halign: 'center', cellWidth: 16 },
      6: { halign: 'center', cellWidth: 18 },
      7: { halign: 'center', fontStyle: 'bold', cellWidth: 18 },
      8: { halign: 'center', cellWidth: 15 },
    },
    showHead: 'everyPage',
    didDrawPage: (data) => {
      const pageNum = (doc.internal as any).getNumberOfPages();
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.text(`Ward Directory • ${hospitalName} Central Health Governance`, margin, pageHeight - 6);
      doc.text(`Page ${data.pageNumber} of ${pageNum}`, pageWidth - margin - 20, pageHeight - 6);
    },
  });

  doc.save(`CHSS_Ward_Directory_${dateStr}.pdf`);
}

