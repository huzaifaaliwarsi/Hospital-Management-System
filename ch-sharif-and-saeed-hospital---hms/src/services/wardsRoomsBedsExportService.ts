export async function downloadBedsExcel(
  beds: Bed[],
  filtersOrUser?: Partial<BedFilterState> | User | null,
  userParam?: User | null
): Promise<void> {
  const isUser = filtersOrUser && ('role' in filtersOrUser || 'username' in filtersOrUser);
  const currentUser = isUser ? (filtersOrUser as User) : userParam;
  const rawFilters = isUser ? null : (filtersOrUser as Partial<BedFilterState> | null);
  const filters: BedFilterState = {
    searchTerm: rawFilters?.searchTerm || '',
    wardId: rawFilters?.wardId || 'All',
    roomId: rawFilters?.roomId || 'All',
    bedType: rawFilters?.bedType || 'All',
    occupancyStatus: rawFilters?.occupancyStatus || 'All',
    operationalStatus: rawFilters?.operationalStatus || 'All',
  };

  const profile = getHospitalProfile();
  const now = new Date();
  const dateStr = getDynamicDateString(now);
  const timeStr = now.toLocaleTimeString('en-PK', { hour: '2-digit', minute: '2-digit' });
  const generatedOn = `${formatDisplayDate(now)}, ${timeStr}`;
  const generatedByName = currentUser?.name || 'Prof. Dr. Tariq Saeed';
  const generatedByRole = currentUser?.role || 'Super Admin';

  const rows = beds.map((b) => ({
    'Bed Code': b.code,
    'Bed Number': b.bedNumber,
    'Room Name': b.roomName,
    'Ward Name': b.wardName,
    'Department Name': b.departmentName,
    'Bed Type': b.bedType,
    'Daily Rate (PKR)': b.dailyBedRate ?? b.dailyRate ?? 0,
    'Occupancy Status': b.occupancyStatus,
    'Operational Status': b.operationalStatus,
    'Current Patient': b.occupancyStatus === 'Occupied' ? b.currentPatientName || 'Occupied' : '',
    'Created By': b.createdBy,
    'Created At': b.createdAt,
    'Updated By': b.updatedBy,
    'Updated At': b.updatedAt,
  }));

  const worksheet1 = XLSX.utils.json_to_sheet(rows);
  worksheet1['!cols'] = [
    { wch: 16 }, { wch: 14 }, { wch: 28 }, { wch: 28 }, { wch: 28 },
    { wch: 16 }, { wch: 16 }, { wch: 16 }, { wch: 18 }, { wch: 36 },
    { wch: 30 }, { wch: 22 }, { wch: 30 }, { wch: 22 },
  ];

  const exportMetadata = [
    { Field: 'Hospital Name', Value: profile.name || 'CH Sharif and Saeed Hospital' },
    { Field: 'Report Title', Value: 'Bed Directory & Operational Status' },
    { Field: 'Generated By', Value: `${generatedByName} (${generatedByRole})` },
    { Field: 'Generated On', Value: generatedOn },
    { Field: 'Total Beds Exported', Value: beds.length },
    { Field: 'Search Query', Value: filters.searchTerm.trim() || 'None' },
    { Field: 'Ward Filter', Value: filters.wardId },
    { Field: 'Room Filter', Value: filters.roomId },
    { Field: 'Bed Type Filter', Value: filters.bedType },
    { Field: 'Occupancy Status Filter', Value: filters.occupancyStatus },
    { Field: 'Operational Status Filter', Value: filters.operationalStatus },
    { Field: 'Hospital Registration No', Value: getProfileFieldValue(profile.registrationNumber) },
    { Field: 'Hospital NTN / Tax No', Value: getProfileFieldValue(profile.taxNumber) },
    { Field: 'Hospital Phone', Value: getProfileFieldValue(profile.primaryPhone) },
  ];

  const worksheet2 = XLSX.utils.json_to_sheet(exportMetadata);
  worksheet2['!cols'] = [{ wch: 28 }, { wch: 50 }];

  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet1, 'Bed Directory');
  XLSX.utils.book_append_sheet(workbook, worksheet2, 'Export Information');

  XLSX.writeFile(workbook, `CHSS_Bed_Directory_${dateStr}.xlsx`);
}

